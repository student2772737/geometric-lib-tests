import math


def area(r):
    '''
    Вычисляет площадь круга по заданному радиусу.
    Параметры:
    r(float, int): радиус круга
    Возвращаемое значение:
    float: площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
        Вычисляет периметр круга по заданному радиусу.
        Параметры:
        r(float, int): радиус круга
        Возвращаемое значение:
        float: периметр(длина окружности)
        '''
    return 2 * math.pi * r

